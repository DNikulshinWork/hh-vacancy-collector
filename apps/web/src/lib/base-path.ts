/**
 * Публичный префикс приложения за обратным прокси (например /proxy/3000).
 * Браузер всегда ходит внутри прокси, поэтому внутренние ссылки на страницы
 * должны начинаться с этого префикса (прокси срежет его при форварде на бэкенд,
 * где маршруты живут на корне).
 */
export const BASE_PATH =
  process.env.NEXT_PUBLIC_WEB_BASE_PATH ?? process.env.WEB_BASE_PATH ?? '';

/** Добавляет публичный префикс к внутреннему пути приложения. */
export function p(pathname: string): string {
  return `${BASE_PATH}${pathname}`;
}
